@app.route("/")
def index():
    return send_from_directory("templates", "index.html")

@app.route("/api/generate-plan", methods=["POST"])
def api_generate_plan():
    data = request.get_json()
    if not data:
        return jsonify({"error": "No data provided"}), 400

    # Input validation
    required_fields = ["name", "age", "diet", "city", "country"]
    for field in required_fields:
        if not data.get(field):
            return jsonify({"error": f"Missing required field: {field}"}), 400

    # Guardrail check
    full_input = " ".join(str(v) for v in data.values())
    is_safe, reason = check_guardrails(full_input)
    if not is_safe:
        return jsonify({"error": f"Content policy violation: {reason}. Please revise your input."}), 400

    try:
        plan = generate_nutrition_plan(data)
        disclaimer = MEDICAL_DISCLAIMER.format(date=datetime.datetime.now().strftime("%B %d, %Y"))
        plan_with_disclaimer = plan + "\n\n" + disclaimer

        # Save to file
        filename = save_plan_to_markdown(data, plan)

        return jsonify({
            "success": True,
            "plan": plan_with_disclaimer,
            "filename": filename,
            "model": MODEL_ID if model else "demo-mode"
        })
    except Exception as e:
        return jsonify({"error": str(e)}), 500


@app.route("/api/chat", methods=["POST"])
def api_chat():
    data = request.get_json()
    question = data.get("question", "").strip()
    user_context = data.get("user_context", {})

    if not question:
        return jsonify({"error": "Question is required"}), 400

    is_safe, reason = check_guardrails(question)
    if not is_safe:
        return jsonify({
            "answer": f"⚠️ I'm unable to respond to that request as it may be harmful. {reason} If you're in distress, please reach out to a healthcare professional or helpline."
        })

    answer = answer_nutrition_query(question, user_context)
    return jsonify({"answer": answer, "model": MODEL_ID if model else "demo-mode"})


@app.route("/api/download/<filename>")
def download_plan(filename):
    # Security: only allow safe filenames
    if not re.match(r'^nutrition_plan_[a-zA-Z0-9_]+\.md$', filename):
        return jsonify({"error": "Invalid filename"}), 400
    return send_from_directory("plans", filename, as_attachment=True)


