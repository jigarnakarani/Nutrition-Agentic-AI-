# ─── Watsonx Model Initialisation ─────────────────────────────────────────────
def get_model():
    if not WATSONX_AVAILABLE:
        return None
    try:
        credentials = Credentials(
            url=WATSONX_URL,
            api_key=WATSONX_API_KEY
        )
        client = APIClient(credentials)
        model = ModelInference(
            model_id=MODEL_ID,
            api_client=client,
            project_id=WATSONX_PROJECT_ID,
            params={
                GenParams.MAX_NEW_TOKENS: 1024,
                GenParams.TEMPERATURE: 0.7,
                GenParams.TOP_P: 0.9,
                GenParams.REPETITION_PENALTY: 1.1,
                GenParams.STOP_SEQUENCES: ["Human:", "User:"]
            }
        )
        return model
    except Exception as e:
        print(f"[ERROR] Watsonx init failed: {e}")
        return None

model = get_model()

# ─── Guardrail Check ───────────────────────────────────────────────────────────
def check_guardrails(text: str) -> tuple[bool, str]:
    """Returns (is_safe, reason)"""
    text_lower = text.lower()
    for keyword in HARMFUL_KEYWORDS:
        if keyword in text_lower:
            return False, f"Request contains potentially harmful content related to '{keyword}'."
    return True, ""

# ─── Nutrition Plan Generator ──────────────────────────────────────────────────
