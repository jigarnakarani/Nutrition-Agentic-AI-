# ─── AI Query Handler ──────────────────────────────────────────────────────────
def answer_nutrition_query(question: str, user_context: dict = None) -> str:
    context_str = ""
    if user_context:
        context_str = f"\nUser context: Age {user_context.get('age','N/A')}, Diet: {user_context.get('diet','N/A')}, Medical: {user_context.get('medical_history','None')}."

    prompt = f"""{SYSTEM_PROMPT}{context_str}

A user asks: "{question}"

Provide a helpful, accurate, and safe nutrition answer. If the question involves a serious medical concern, recommend consulting a healthcare professional. Keep the response concise (under 200 words) and practical.

Answer:"""

    if model:
        try:
            return model.generate_text(prompt=prompt)
        except Exception as e:
            print(f"[ERROR] Query inference failed: {e}")

    return generate_demo_answer(question, user_context)


def generate_demo_answer(question: str, user_context: dict = None) -> str:
    q = question.lower()
    if "protein" in q:
        is_veg = user_context and "veg" in user_context.get("diet","").lower() and "non" not in user_context.get("diet","").lower()
        sources = "lentils, chickpeas, tofu, paneer, Greek yogurt, quinoa" if is_veg else "chicken, fish, eggs, lentils, Greek yogurt"
        return f"Excellent question! Protein is essential for muscle repair and immune function. Great sources include: **{sources}**. Aim for 0.8–1.2g of protein per kg of body weight daily. Distribute protein intake across all meals for optimal absorption. 💪"
    if "diabetes" in q or "blood sugar" in q or "sugar" in q:
        return "For blood sugar management, focus on **low-glycaemic index (GI) foods**: oats, brown rice, legumes, non-starchy vegetables. Avoid sugary drinks and refined carbohydrates. The **plate method** works well — 50% non-starchy veggies, 25% lean protein, 25% complex carbs. Always monitor levels with your doctor. 🩺"
    if "weight loss" in q or "lose weight" in q:
        return "Sustainable weight loss comes from a **modest calorie deficit (300–500 kcal/day)** combined with regular physical activity. Focus on high-fibre, high-protein foods that keep you full. Avoid crash diets — they often lead to muscle loss and nutrient deficiencies. Consistency over 4–8 weeks shows real results. 🌟"
    if "water" in q or "hydrat" in q:
        return "Hydration is foundational to health! Aim for **2–2.5 litres (8–10 glasses)** of water daily. Increase intake during exercise, hot weather, or illness. Herbal teas and coconut water count too. A simple rule: your urine should be pale yellow — that's your hydration indicator! 💧"
    if "vitamin" in q or "mineral" in q or "supplement" in q:
        return "Before taking any supplement, get a **blood test** to identify actual deficiencies. Common ones include Vitamin D, B12, Iron, and Omega-3. Food-first is always the best approach — supplements fill gaps, not replace a balanced diet. Always consult your doctor before starting supplements. 🌿"
    return f"Great question about **{question[:50]}**! A balanced diet rich in whole grains, lean proteins, healthy fats, and abundant vegetables forms the cornerstone of good nutrition. Personalised advice depends on your specific health goals and medical history. I'd recommend consulting a registered dietitian for a tailored plan. Feel free to ask me anything more specific! 😊"


# ─── Save Nutrition Plan to Markdown ──────────────────────────────────────────
def save_plan_to_markdown(user_data: dict, plan: str) -> str:
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    name_safe = re.sub(r'[^a-zA-Z0-9]', '_', user_data.get("name", "user"))
    filename = f"nutrition_plan_{name_safe}_{timestamp}.md"
    filepath = os.path.join("plans", filename)
    os.makedirs("plans", exist_ok=True)

    disclaimer = MEDICAL_DISCLAIMER.format(date=datetime.datetime.now().strftime("%B %d, %Y"))
    full_content = f"# Nutrition Plan — {user_data.get('name', 'User')}\n\n{plan}\n\n{disclaimer}"

    with open(filepath, "w", encoding="utf-8") as f:
        f.write(full_content)

    return filename


